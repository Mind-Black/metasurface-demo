"""Regenerates src/lib/optics/unitCellTable.ts from RCWA (run from this directory).

The dispersion formulas here must stay identical to src/lib/optics/materials.ts.
Usage: python generate_unit_cell_table.py [--check]
"""
import json
import multiprocessing as mp
import sys
import time
from pathlib import Path

import numpy as np

from rcwa import pillar_grid, slab, solve

PITCH_UM = 0.25
HEIGHT_UM = 0.6
TRUNCATION = 7
DIAMETERS_NM = list(range(60, 211, 5))
WAVELENGTHS_NM = list(range(400, 700, 10)) + list(range(700, 1551, 50))


def n_tio2(lam):
    rutile2 = 5.913 + .2441/(lam*lam - .0803)
    n = np.sqrt(1 + .847*(rutile2 - 1))
    return n + 1j*(.08*np.exp(-(lam - .38)/.02))


def n_sio2(lam):
    l2 = lam*lam
    return np.sqrt(1 + .6961663*l2/(l2 - .0684043**2) + .4079426*l2/(l2 - .1162414**2)
                   + .8974794*l2/(l2 - 9.896161**2))


def cell(args):
    d_nm, lam_nm, N = args
    lam = lam_nm/1000
    ns = n_sio2(lam)
    grid = pillar_grid(PITCH_UM, d_nm/1000, n_tio2(lam)**2)
    s = solve(PITCH_UM, lam, HEIGHT_UM, grid, ns**2, N=N)
    # Scale so |t|^2 is the power fraction in the zeroth order, phase relative to an empty cell.
    empty = slab(ns, 1.0, HEIGHT_UM, lam)
    t = np.sqrt(1/ns)*abs(s['t00'])*np.exp(1j*np.angle(s['t00']/empty))
    return float(t.real), float(t.imag), float(s['R'] + s['T'])


def check():
    for lam_nm in (400, 532, 1550):
        for d in (120, 170, 205):
            line = [cell((d, lam_nm, N)) for N in (4, 7, 10)]
            ts = [complex(a, b) for a, b, _ in line]
            print(lam_nm, d, [f'{abs(t):.3f}/{np.angle(t):+.3f}' for t in ts],
                  f'|t7-t10|={abs(ts[1]-ts[2]):.3f} R+T={line[2][2]:.4f}', flush=True)


def main():
    t0 = time.time()
    jobs = [(d, lam, TRUNCATION) for lam in WAVELENGTHS_NM for d in DIAMETERS_NM]
    with mp.Pool(max(1, mp.cpu_count() - 2)) as pool:
        out = pool.map(cell, jobs, chunksize=8)
    budget = np.array([o[2] for o in out])
    print(f'{len(jobs)} cells in {time.time()-t0:.0f}s; R+T range {budget.min():.4f}..{budget.max():.4f}')
    re = [round(o[0], 4) for o in out]
    im = [round(o[1], 4) for o in out]
    target = Path(__file__).resolve().parents[2]/'src/lib/optics/unitCellTable.ts'
    target.write_text(f"""// Generated by tools/rcwa/generate_unit_cell_table.py. Do not edit by hand.
// RCWA zeroth-order transmission of TiO2 pillars on SiO2, normal incidence from the substrate.
// t[w * diameters.length + d] = re + i im, |t|^2 = power in the zeroth order.

export const UNIT_CELL_TABLE = {{
  pitchNm: {round(PITCH_UM*1000)},
  heightNm: {round(HEIGHT_UM*1000)},
  diametersNm: {json.dumps(DIAMETERS_NM)},
  wavelengthsNm: {json.dumps(WAVELENGTHS_NM)},
  re: {json.dumps(re, separators=(',', ':'))},
  im: {json.dumps(im, separators=(',', ':'))},
}} as const;
""", encoding='utf-8')
    print('wrote', target)


if __name__ == '__main__':
    check() if '--check' in sys.argv else main()
