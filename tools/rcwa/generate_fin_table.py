"""Regenerates src/lib/optics/finCellTable.ts from RCWA (run from this directory).

Rectangular TiO2 nanofins on SiO2 for Pancharatnam-Berry (geometric) phase metasurfaces. Each fin is
solved aligned with x; its Jones matrix is diag(tL, tS) (long and short axis). Rotation is applied
analytically in the browser, under the same locally periodic approximation as the pillars.
Usage: python generate_fin_table.py [--check]
"""
import json
import multiprocessing as mp
import os
import sys
import time
from pathlib import Path

# One BLAS thread per pool worker: otherwise every worker spawns a thread per core and the pool
# runs hundreds of times slower than a single process.
for var in ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS'):
    os.environ.setdefault(var, '1')

import numpy as np  # noqa: E402

from generate_unit_cell_table import HEIGHT_UM, PITCH_UM, WAVELENGTHS_NM, n_sio2, n_tio2
from rcwa import rect_grid, slab, solve

TRUNCATION = 7
LENGTHS_NM = list(range(100, 211, 10))  # keeps a >= 40 nm gap at 250 nm pitch
WIDTHS_NM = list(range(50, 111, 10))


def cell(args):
    L_nm, W_nm, lam_nm, N = args
    lam = lam_nm/1000
    ns = n_sio2(lam)
    grid = rect_grid(PITCH_UM, L_nm/1000, W_nm/1000, n_tio2(lam)**2)
    s = solve(PITCH_UM, lam, HEIGHT_UM, grid, ns**2, N=N)
    empty = slab(ns, 1.0, HEIGHT_UM, lam)
    # Same scaling as the pillar table: |t|^2 is power in the zeroth order, phase relative to an empty cell.
    norm = lambda t: np.sqrt(1/ns)*abs(t)*np.exp(1j*np.angle(t/empty))
    tL, tS = norm(s['txx']), norm(s['tyy'])
    cross = max(abs(s['txy']), abs(s['tyx']))
    return float(tL.real), float(tL.imag), float(tS.real), float(tS.imag), float(cross), float(s['R'] + s['T'])


def check():
    for lam_nm in (450, 532, 650):
        for L, W in ((180, 70), (200, 90)):
            line = [cell((L, W, lam_nm, N)) for N in (4, 7, 10)]
            fmt = lambda o: f'tL {abs(complex(o[0], o[1])):.3f}/{np.angle(complex(o[0], o[1])):+.3f} ' \
                            f'tS {abs(complex(o[2], o[3])):.3f}/{np.angle(complex(o[2], o[3])):+.3f}'
            d = [abs(complex(o[0], o[1]) - complex(o[2], o[3]))**2/4 for o in line]
            print(lam_nm, L, W, ' | '.join(fmt(o) for o in line),
                  f'|d|^2={d[0]:.3f}/{d[1]:.3f}/{d[2]:.3f} |txy|max={max(o[4] for o in line):.1e}', flush=True)


def main():
    t0 = time.time()
    jobs = [(L, W, lam, TRUNCATION) for lam in WAVELENGTHS_NM for L in LENGTHS_NM for W in WIDTHS_NM]
    with mp.Pool(max(1, mp.cpu_count() - 2)) as pool:
        out = pool.map(cell, jobs, chunksize=8)
    cross = max(o[4] for o in out)
    budget = np.array([o[5] for o in out])
    print(f'{len(jobs)} cells in {time.time()-t0:.0f}s; R+T range {budget.min():.4f}..{budget.max():.4f}; '
          f'max |t_xy| {cross:.1e}')
    cols = [[round(o[k], 4) for o in out] for k in range(4)]
    dump = lambda v: json.dumps(v, separators=(',', ':'))
    target = Path(__file__).resolve().parents[2]/'src/lib/optics/finCellTable.ts'
    target.write_text(f"""// Generated by tools/rcwa/generate_fin_table.py. Do not edit by hand.
// RCWA zeroth-order transmission of rectangular TiO2 nanofins on SiO2, normal incidence from the substrate,
// fin long axis along x. tL: x-polarized (long axis), tS: y-polarized (short axis).
// Index [(w * lengthsNm.length + l) * widthsNm.length + k], |t|^2 = power in the zeroth order.

export const FIN_CELL_TABLE = {{
  pitchNm: {round(PITCH_UM*1000)},
  heightNm: {round(HEIGHT_UM*1000)},
  lengthsNm: {json.dumps(LENGTHS_NM)},
  widthsNm: {json.dumps(WIDTHS_NM)},
  wavelengthsNm: {json.dumps(WAVELENGTHS_NM)},
  longRe: {dump(cols[0])},
  longIm: {dump(cols[1])},
  shortRe: {dump(cols[2])},
  shortIm: {dump(cols[3])},
}} as const;
""", encoding='utf-8')
    print('wrote', target)


if __name__ == '__main__':
    check() if '--check' in sys.argv else main()
